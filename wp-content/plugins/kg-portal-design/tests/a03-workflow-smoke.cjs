'use strict';
/** Offline, no WordPress or database writes. Run: node tests/a03-workflow-smoke.cjs */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {positiveId, copyIntakeFields, checkRelations} = require('../assets/a03-workflow.js');
let checks=0;
function ok(message){checks++;console.log('PASS:',message)}
(async()=>{
  for(const v of [0,-1,'', 'abc','10a',1.25,'9007199254740992']) assert.equal(positiveId(v),false);
  assert.equal(positiveId('32'),true);ok('Only valid positive IDs are accepted');
  const row={public_id:'2026-admissions',university_id:23,academic_year:2026,academic_term:'fall',admission_type:'international',start_date:'2026-05-01',end_date:'2026-05-22',application_url:'https://example.ac.kr',published_version:10,source_id:99};
  const copied=copyIntakeFields(row);
  assert.equal(copied.university_id,'23');
  assert.equal(copied.public_id,'');
  assert.equal(copied.academic_year,'');
  assert.equal(copied.academic_term,'fall');
  assert.equal(copied.admission_type,'international');
  for(const k of ['start_date','end_date','application_url'])assert.equal(copied[k],'');
  for(const k of ['published_version','source_id','id','approval_status'])assert.equal(k in copied,false);
  ok('Duplicate intake is a new, unapproved draft without stale IDs, year, dates, links or source');
  const data={campus:{id:12,university_id:23},program:{id:31,university_id:23,campus_id:12},intake:{id:44,university_id:23}};
  const visited=[];
  const resolve=async(type,id)=>{visited.push(type+'/'+id);return data[type]?.id===id?data[type]:null;};
  assert.equal(await checkRelations('program',{university_id:'23',campus_id:'12'},resolve),true);
  ok('Campus within selected university is allowed');
  await assert.rejects(checkRelations('program',{university_id:'24',campus_id:'12'},resolve),/캠퍼스/);
  await assert.rejects(checkRelations('program',{university_id:'23',campus_id:'999'},resolve),/캠퍼스/);
  ok('Cross-university and unknown campus are rejected');
  assert.equal(await checkRelations('offering',{program_id:'31',intake_id:'44'},resolve),true);
  ok('Offering program/intake within one university are allowed');
  const wrongResolve=async(type,id)=>type==='intake'?{id,university_id:7}:resolve(type,id);
  await assert.rejects(checkRelations('offering',{program_id:'31',intake_id:'44'},wrongResolve),/같은 대학/);
  await assert.rejects(checkRelations('offering',{program_id:'31',intake_id:'999'},resolve),/같은 대학/);
  await assert.rejects(checkRelations('offering',{program_id:'',intake_id:'44'},resolve),/전공/);
  ok('Cross-university offering, missing and invalid relationships are rejected');
  assert.equal(await checkRelations('intake',{university_id:'23',academic_year:'2027',start_date:'',end_date:''},resolve),true);
  await assert.rejects(checkRelations('intake',{university_id:'23',academic_year:'2026',start_date:'2026-11-02',end_date:'2026-11-01'},resolve),/시작일/);
  await assert.rejects(checkRelations('intake',{university_id:'23',academic_year:''},resolve),/학년도/);
  ok('New intake year is required and inverted dates are blocked');
  const source = fs.readFileSync(path.join(__dirname,'../assets/a03-workflow.js'),'utf8');
  const plugin = fs.readFileSync(path.join(__dirname,'../kg-portal-design.php'),'utf8');
  assert.match(source,/form\.requestSubmit\(\)/);
  assert.match(source,/kgpa-entity-create-form/);
  assert.match(source,/checkbox\.required = true/);
  assert.match(source,/source.*never|출처 연결은 복제하지 않습니다/);
  assert.match(plugin, /\$page==='kgp-operator-entities'/);
  assert.match(plugin,/\['kgp-operator','kgds-relations'\]/);
  ok('Original Admin native create handler is retained; A03 enhancer is strictly scoped');
  console.log(`SUCCESS: ${checks} A03 offline contract groups passed. No writes performed.`);
})().catch(error=>{console.error(error);process.exitCode=1});
