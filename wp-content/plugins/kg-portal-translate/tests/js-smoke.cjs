const assert = require('node:assert/strict');
const api = require('../assets/auto-translate.js');
const languages = {ko:'Korean',en:'English',vi:'Vietnamese',fr:'French','zh-TW':'Traditional Chinese','zh-CN':'Simplified Chinese',ar:'Arabic'};
const config = {languages, source:'en'};
assert.equal(api.locale('vi-VN', languages), 'vi');
assert.equal(api.locale('zh-Hant', languages), 'zh-TW');
assert.equal(api.locale('zh-HK', languages), 'zh-TW');
assert.equal(api.locale('zh-CN', languages), 'zh-CN');
assert.equal(api.locale('en-US', languages), 'en');
assert.equal(api.locale('xx-XX', languages), null);
assert.deepEqual(api.preferred(config, { languages:['vi-VN','en-US'] }, {getItem:()=>null}), {language:'vi',setting:'auto'});
assert.deepEqual(api.preferred(config, {languages:['vi-VN']}, {getItem:()=> 'ko'}), {language:'ko',setting:'ko'});
assert.equal(api.preferred(config, {languages:['unknown']}, {getItem:()=>null}).language, 'en');
assert.equal(api.norm(' Public\u00a0 information \n for students '),'Public information for students');
assert.equal(api.eligible('Find universities'),true);
assert.equal(api.eligible('한국 유학 가이드'),true);
assert.equal(api.eligible('日本の大学'),true);
assert.equal(api.eligible('Tuition 2027'),false);
assert.equal(api.eligible('secret@example.com'),false);
assert.equal(api.eligible('https://example.test'),false);
assert.equal(api.isSafe({nodeType:3,parentElement:{tagName:'P',parentElement:null,hasAttribute:()=>false,getAttribute:()=>null,classList:[]}}),true);
assert.equal(api.isSafe({nodeType:3,parentElement:{tagName:'TEXTAREA',parentElement:null,hasAttribute:()=>false,getAttribute:()=>null,classList:[]}}),false);
console.log('PASS: browser language, explicit preference, text privacy filters and no-DOM Node import.');
